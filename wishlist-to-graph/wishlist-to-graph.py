def walk(client: Client, envelope: dict[str, Any]) -> None:
    target = (envelope.get("WISHLIST") or envelope.get("wishlist") or "").strip()
    html_file = (envelope.get("html-file") or "").strip()
    domain = (envelope.get("domain") or "amazon.com").strip().lower()
    domain = domain[4:] if domain.startswith("www.") else domain
    delay_ms = int(envelope.get("delay-ms") or 1500)
    max_items = int(envelope.get("max-items") or 0)
    contact = (envelope.get("contact") or "").strip()
    skip_enrich = bool(envelope.get("skip-enrich"))
    use_google = bool(envelope.get("google-books"))
    use_hardcover = bool(envelope.get("hardcover"))
    use_wikidata = bool(envelope.get("wikidata"))
    geocode = bool(envelope.get("geocode"))
    geocode_limit = int(envelope.get("geocode-limit") or 0)
    row_cap = int(client.caps.get("maxRowsPerStatement") or 1000)
    row_chunk = max(1, min(500, row_cap))

    if not html_file and not target:
        if geocode:
            for statement in SCHEMA:
                client.call("update_schema", {"statement": statement})
            stats = geocode_places(client, contact=contact, limit=geocode_limit, row_chunk=row_chunk)
            client.call("report_output", {"text": geocode_summary(stats, standalone=True), "starters": GEO_STARTERS})
            return
        raise SystemExit(f"{NAME}: give the wishlist URL as the positional argument, e.g. "
                         "relate run wishlist-to-graph https://www.amazon.com/hz/wishlist/ls/XXXXXXXXXXXX -d ./books.rl "
                         "(or pass --geocode alone to geocode the places of an existing store)")

    # 1. The wishlist: fetched live or read from a saved page.
    if html_file:
        with open(html_file, encoding="utf-8", errors="replace") as handle:
            page = handle.read()
        inferred_domain, inferred_id = parse_wishlist_target(target, domain) if target else (domain, None)
        domain = inferred_domain
        list_id = inferred_id or first(r'id="listId"[^>]*value="([^"]*)"', page) or first(r'value="([^"]*)"[^>]*id="listId"', page)
        if not list_id:
            canonical = first(r'<link[^>]*rel="canonical"[^>]*href="([^"]*)"', page)
            list_id = (parse_wishlist_target(canonical, domain)[1] if canonical else None) or os.path.splitext(os.path.basename(html_file))[0]
        pages = [page]
        log(f"parsing saved page {html_file}")
    else:
        domain, list_id = parse_wishlist_target(target, domain)
        log(f"fetching wishlist {list_id or target} from {domain}")
        domain, list_id, pages = fetch_wishlist_pages(domain, list_id, target, delay_ms)
        log(f"fetched {len(pages)} page(s)")

    meta = parse_list_meta(pages[0], domain, list_id)
    items = parse_items(pages, domain)
    if max_items > 0:
        items = items[:max_items]
    if not items:
        raise SystemExit(
            f"{NAME}: no items found on the list {list_id} — it may be empty, private, "
            "or Amazon served a page without the list markup (try --delay-ms 4000 or --html-file)"
        )
    books = [i for i in items if i["is_book"]]
    log(f"{len(items)} items, {len(books)} look like books")

    # 2. Schema — idempotent, so a re-run against the same store is a refresh.
    for statement in SCHEMA:
        client.call("update_schema", {"statement": statement})

    # 3. The wishlist and every item.
    client.call(
        "write_cypher",
        {
            "statement": WRITE_WISHLIST,
            "parameters": {
                "id": meta["id"],
                "title": meta["title"],
                "description": meta["description"],
                "owner": meta["owner"],
                "domain": domain,
                "url": meta["url"],
                "item_count": len(items),
                "book_count": len(books),
            },
        },
    )
    item_rows = []
    for item in items:
        row = {k: v for k, v in item.items() if k != "contributors"}
        row["contributor_names"] = [c["name"] for c in item["contributors"]] or None
        item_rows.append(row)
    for statement, subset in (
        (WRITE_BOOK_ITEMS, [r for r in item_rows if r["is_book"]]),
        (WRITE_OTHER_ITEMS, [r for r in item_rows if not r["is_book"]]),
    ):
        for chunk in chunks(subset, row_chunk):
            client.call("write_cypher", {"statement": statement, "parameters": {"rows": chunk, "wishlist": meta["id"]}})

    # 4. Enrichment.
    enriched = 0
    unresolved: list[dict[str, Any]] = []
    sources_used: list[str] = []
    ol = OpenLibrary(contact)
    google = GoogleBooks(os.environ.get("GOOGLE_BOOKS_API_KEY", "")) if use_google else None
    hardcover = Hardcover(os.environ.get("HARDCOVER_API_TOKEN", "")) if use_hardcover else None
    wikidata = Wikidata(contact) if use_wikidata else None
    if google and not google.key:
        log("--google-books set but GOOGLE_BOOKS_API_KEY is empty; the anonymous quota is 0/day, skipping Google Books")
        google = None
    if hardcover and not os.environ.get("HARDCOVER_API_TOKEN"):
        log("--hardcover set but HARDCOVER_API_TOKEN is empty; skipping Hardcover")
        hardcover = None

    author_qids: dict[str, str] = {}  # author key -> QID
    work_qids: dict[str, str] = {}  # book key -> QID

    if not skip_enrich:
        sources_used.append("Open Library")
        candidates = [i for i in items if i["is_book"] or not i["external"]]
        for index, item in enumerate(candidates, start=1):
            try:
                result = enrich_from_open_library(ol, item)
            except SystemExit:
                raise
            except Exception as error:  # one bad record never fails the run
                log(f"[{index}/{len(candidates)}] {item['asin']}: open library error {error!r}")
                result = None
            if not result:
                if item["is_book"]:
                    unresolved.append(item)
                    log(f"[{index}/{len(candidates)}] {item['title'][:60]!r}: no Open Library match")
                continue
            enriched += 1
            book = result["book"]
            key = book["key"]
            log(f"[{index}/{len(candidates)}] {item['title'][:60]!r} → {key} ({book.get('match')})")
            statements: list[dict[str, Any]] = [
                {"statement": WRITE_ENRICHED_BOOK, "parameters": {"book": book, "asin": item["asin"], "edition": result["edition"]}},
            ]
            if result["authors"]:
                statements.append({"statement": WRITE_AUTHORS, "parameters": {"key": key, "authors": result["authors"]}})
            if result["publisher"]:
                statements.append({"statement": WRITE_PUBLISHER, "parameters": {"asin": item["asin"], "name": result["publisher"]}})
            for label, rel, names in (
                ("Subject", "ABOUT", result["subjects"]),
                ("Place", "SET_IN", result["places"]),
                ("Person", "FEATURES", result["people"]),
                ("Era", "SET_DURING", result["times"]),
                ("Genre", "IN_GENRE", result["genres"]),
            ):
                if names:
                    statements.append({"statement": term_statement(label, rel), "parameters": {"key": key, "names": names}})
            if book.get("wikidata"):
                work_qids[key] = book["wikidata"]
            for author in result["authors"]:
                if author["props"].get("wikidata"):
                    author_qids[author["key"]] = author["props"]["wikidata"]

            if google:
                extra = google.lookup(item, result["edition"])
                if extra:
                    if "Google Books" not in sources_used:
                        sources_used.append("Google Books")
                    if extra["props"]:
                        statements.append({"statement": WRITE_BOOK_PROPS, "parameters": {"key": key, "props": extra["props"]}})
                    if extra["genres"]:
                        statements.append({"statement": term_statement("Genre", "IN_GENRE"), "parameters": {"key": key, "names": extra["genres"]}})
            if hardcover:
                extra = hardcover.lookup(item, result["edition"])
                if extra:
                    if "Hardcover" not in sources_used:
                        sources_used.append("Hardcover")
                    if extra["props"]:
                        statements.append({"statement": WRITE_BOOK_PROPS, "parameters": {"key": key, "props": extra["props"]}})
                    if extra["genres"]:
                        statements.append({"statement": term_statement("Genre", "IN_GENRE"), "parameters": {"key": key, "names": extra["genres"]}})
                    if extra["series"]:
                        statements.append({"statement": WRITE_SERIES, "parameters": {"key": key, "series": extra["series"]}})
            client.call("batch_cypher", {"statements": statements})

    # 5. Books Open Library did not know (or enrichment skipped): a Book per
    #    edition from the Amazon data, with byline authors.
    fallback_items = [i for i in books if skip_enrich] + unresolved
    fallback_rows = [
        {
            "asin": i["asin"],
            "key": f"amazon:{i['asin']}",
            "title": re.split(r"\s[:(\[]", i["title"])[0].strip() or i["title"],
            "image_url": i["image_url"],
            "url": i["url"],
            "contributors": [
                {"key": "name:" + re.sub(r"[^a-z0-9]+", "-", c["name"].lower()).strip("-"), "name": c["name"], "role": c["role"]}
                for c in i["contributors"]
            ],
        }
        for i in fallback_items
    ]
    for chunk in chunks(fallback_rows, row_chunk):
        client.call("write_cypher", {"statement": WRITE_FALLBACK_BOOKS, "parameters": {"rows": chunk}})

    # 6. Wikidata — one pass over every QID collected above.
    if wikidata and (author_qids or work_qids):
        sources_used.append("Wikidata")
        facts = wikidata.facts(WIKIDATA_AUTHORS, list(author_qids.values()))
        articles = wikidata.facts(WIKIDATA_ARTICLES, list(author_qids.values()))
        for author_key, qid in author_qids.items():
            rows = facts.get(qid, [])
            if not rows and not articles.get(qid):
                continue
            by_prop: dict[str, list[dict[str, Any]]] = {}
            for row in rows:
                by_prop.setdefault(row["prop"], []).append(row)
            props = drop_none(
                {
                    "occupations": dedupe([r["label"] for r in by_prop.get("P106", [])]) or None,
                    "languages": dedupe([r["label"] for r in by_prop.get("P1412", [])]) or None,
                    "native_language": next((r["label"] for r in by_prop.get("P103", [])), None),
                    "wikidata_birth_date": next((r["value"][:10] for r in by_prop.get("P569", [])), None),
                    "wikidata_death_date": next((r["value"][:10] for r in by_prop.get("P570", [])), None),
                    "image_url": next((r["value"] for r in by_prop.get("P18", [])), None),
                    "wikipedia_url": next((r["article"] for r in articles.get(qid, []) if r.get("article")), None),
                    "wikidata_url": f"https://www.wikidata.org/wiki/{qid}",
                }
            )
            client.call(
                "write_cypher",
                {
                    "statement": WRITE_AUTHOR_FACTS,
                    "parameters": {
                        "key": author_key,
                        "props": props,
                        "countries": dedupe([r["label"] for r in by_prop.get("P27", [])]),
                        "birthplace": dedupe([r["label"] for r in by_prop.get("P19", [])])[:1],
                        "awards": [{"name": r["label"], "qid": r["qid"]} for r in by_prop.get("P166", []) if r["label"] and not re.fullmatch(r"Q\d+", r["label"])],
                    },
                },
            )
        work_facts = wikidata.facts(WIKIDATA_WORKS, list(work_qids.values()))
        for book_key, qid in work_qids.items():
            rows = work_facts.get(qid, [])
            if not rows:
                continue
            by_prop = {}
            for row in rows:
                by_prop.setdefault(row["prop"], []).append(row)
            statements = []
            props = drop_none(
                {
                    "wikidata_url": f"https://www.wikidata.org/wiki/{qid}",
                    "wikidata_publication_date": next((r["value"][:10] for r in by_prop.get("P577", [])), None),
                    "form": next((r["label"] for r in by_prop.get("P7937", [])), None),
                    "original_language": next((r["label"] for r in by_prop.get("P407", [])), None),
                    "main_subjects": dedupe([r["label"] for r in by_prop.get("P921", [])]) or None,
                }
            )
            statements.append({"statement": WRITE_BOOK_PROPS, "parameters": {"key": book_key, "props": props}})
            genres = dedupe([r["label"] for r in by_prop.get("P136", []) if not re.fullmatch(r"Q\d+", r["label"])])
            if genres:
                statements.append({"statement": term_statement("Genre", "IN_GENRE"), "parameters": {"key": book_key, "names": genres}})
            places = dedupe([r["label"] for r in by_prop.get("P840", []) if not re.fullmatch(r"Q\d+", r["label"])])
            if places:
                statements.append({"statement": term_statement("Place", "SET_IN"), "parameters": {"key": book_key, "names": places}})
            series = {}
            for r in by_prop.get("P179", []):
                if r["label"] and not re.fullmatch(r"Q\d+", r["label"]):
                    position = series.get(r["label"], {}).get("position")
                    series[r["label"]] = {"name": r["label"], "position": r.get("ordinal") or position}
            if series:
                statements.append({"statement": WRITE_SERIES, "parameters": {"key": book_key, "series": list(series.values())}})
            awards = {}
            for r in by_prop.get("P166", []):
                if r["label"] and not re.fullmatch(r"Q\d+", r["label"]):
                    year = r["when"][:4] if r.get("when") else None
                    awards[r["label"]] = {"name": r["label"], "qid": r["qid"], "year": int(year) if year and year.isdigit() else None}
            if awards:
                statements.append({"statement": WRITE_BOOK_AWARDS, "parameters": {"key": book_key, "awards": list(awards.values())}})
            client.call("batch_cypher", {"statements": statements})

    # 7. Byline-only authors whose placeholder Book was replaced by an Open
    #    Library work (step 4 deletes the placeholder) are now orphans.
    client.call("write_cypher", {"statement": DELETE_ORPHAN_AUTHORS, "parameters": {}})

    # 7b. Geocode the places (opt-in): every Place without a location yet.
    geo_stats = geocode_places(client, contact=contact, limit=geocode_limit, row_chunk=row_chunk) if geocode else None

    # 8. Verify and report.
    found = client.call("read_cypher", {"statement": VERIFY})
    counts = found["rows"][0] if found.get("rows") else {}
    summary = (
        f"{NAME}: {meta['title']!r} ({domain}) — {counts.get('items', 0)} items, "
        f"{counts.get('editions', 0)} book editions, {counts.get('books', 0)} books "
        f"({counts.get('enriched', 0)} enriched), {counts.get('authors', 0)} authors, "
        f"{counts.get('subjects', 0)} subjects, {counts.get('genres', 0)} genres, "
        f"{counts.get('places', 0)} places"
    )
    if "located_places" in counts:
        summary += f" ({counts.get('located_places') or 0} on the map)"
    if counts.get("awards") or counts.get("series"):
        summary += f", {counts.get('awards', 0)} awards, {counts.get('series', 0)} series"
    if sources_used:
        summary += f" — sources: {', '.join(sources_used)}"
    if unresolved:
        summary += f"; {len(unresolved)} book(s) had no Open Library match and carry Amazon data only"
    if geo_stats is not None:
        summary += "; " + geocode_summary(geo_stats, standalone=False)
    client.call("report_output", {"text": summary, "starters": STARTERS + (GEO_STARTERS if geocode else [])})


def main() -> None:
    if sys.argv[1:] == ["--self-test"]:  # offline checks; the host never passes this
        raise SystemExit(self_test())
    client = Client()
    walk(client, client.start())


if __name__ == "__main__":
    main()
