@dataclass
class GeoHeading:
    name: str
    status: str  # 'lookup' | 'manual' | 'skipped'
    query: str | None = None
    fallback_query: str | None = None
    countrycodes: str | None = None
    featuretype: str | None = None
    label_base: str = ""
    canonical: bool = False
    qualifier_label: str | None = None
    bare_single_word: bool = False
    lat: float | None = None
    lon: float | None = None
    reason: str | None = None


def skip_reason(heading: str, base: str | None, qual: str | None) -> str | None:
    """Why a heading gets no coordinates at all (E7), or None."""
    k = fold(heading)
    keys = {k} | ({fold(base)} if base else set())
    for key in keys:
        if key in SKIP_SPACE:
            return "non-terrestrial"
        if key in SKIP_FICTIONAL:
            return "fictional setting"
        if key in SKIP_NOT_PLACE:
            return "not a place"
    if qual is not None:
        folded_qual = fold(qual)
        if CELESTIAL_QUALIFIER.search(folded_qual):
            return "fictional setting" if FICTIONAL_QUALIFIER.search(folded_qual) else "non-terrestrial"
    if STAR_SYSTEM.match(k) or MARS_FEATURE.search(k):
        return "non-terrestrial"
    if NON_PLACE.match(k):
        return "unresolved Wikidata id" if WIKIDATA_ID.match(k) else "fictional setting"
    return None


def _drop_generic_suffix(text: str) -> str | None:
    words = text.split()
    if len(words) >= 2 and words[-1].casefold() in GENERIC_SUFFIXES:
        return " ".join(words[:-1])
    return None


def normalize_heading(name: str) -> GeoHeading:
    """One stored Place heading -> how to geocode it. Pure: no I/O."""
    heading = re.sub(r"\s+", " ", unicodedata.normalize("NFC", name or "")).strip()
    if ";" in heading:
        heading = heading.split(";", 1)[0].strip()
    opens, closes = heading.count("("), heading.count(")")
    if closes > opens or not re.search(r"[^\W\d_]", heading):
        return GeoHeading(name=name, status="skipped", label_base=heading, reason="malformed heading")
    if opens > closes:
        heading += ")" * (opens - closes)

    match = QUALIFIED.match(heading)
    base = match.group("base").strip() if match else None
    qual = match.group("qual").strip() if match else None
    reason = skip_reason(heading, base, qual)
    if reason:
        return GeoHeading(name=name, status="skipped", label_base=base or heading, reason=reason)

    k = fold(heading)
    if k in SYNONYMS:
        canonical = SYNONYMS[k]
        if canonical in MANUAL_REGIONS:
            lat, lon = MANUAL_REGIONS[canonical]
            return GeoHeading(name=name, status="manual", label_base=canonical, canonical=True, lat=lat, lon=lon)
        return GeoHeading(
            name=name,
            status="lookup",
            query=QUERY_OVERRIDES.get(canonical, canonical),
            countrycodes=CANON_CC.get(canonical),
            label_base=canonical,
            canonical=True,
        )

    if match:
        featuretype = None
        countrycodes = None
        label_base = base
        if fold(qual) in STATE_QUALIFIERS:
            if fold(base) in US_STATE_NAMES:
                countrycodes = "us"
            base = f"{base} State"
            label_base = base
            featuretype = "state"
            qual = ""
        if " : " in qual:
            left, right = qual.split(" : ", 1)
            base = f"{base} {right.strip()}"
            label_base = base
            qual = left.strip()
        qual = qual.replace("New York, N.Y.", "New York City")
        expanded: list[str] = []
        second_half: str | None = None  # "Idaho and Mont." -> Montana, tried when Idaho finds nothing
        for part in qual.split(","):
            part = part.strip()
            if not part:
                continue
            if " and " in part and part not in KNOWN_AND_NAMES:
                part, other = (x.strip() for x in part.split(" and ", 1))
                if second_half is None and other:
                    second_half = QUALIFIER_EXPANSIONS.get(other, other)
            if "-" in part:
                head = part.split("-", 1)[0].strip()
                if head in QUALIFIER_EXPANSIONS or head in COUNTRY_CODES:
                    part = head
            expanded.append(QUALIFIER_EXPANSIONS.get(part, part))
        for part in reversed(expanded):
            if part in COUNTRY_CODES:
                countrycodes = COUNTRY_CODES[part]
                break
        tail = (", " + ", ".join(expanded)) if expanded else ""
        query = base + tail
        stripped = _drop_generic_suffix(base)
        fallback = (stripped + tail) if stripped else None
        if fallback is None and second_half and expanded:
            fallback = ", ".join([base, second_half, *expanded[1:]])
        return GeoHeading(
            name=name,
            status="lookup",
            query=query,
            fallback_query=fallback,
            countrycodes=countrycodes,
            featuretype=featuretype,
            label_base=label_base,
            qualifier_label=expanded[0] if expanded else None,
        )

    us_bare = US_STATE_NAMES - {"washington", "georgia", "new york"}
    return GeoHeading(
        name=name,
        status="lookup",
        query=heading,
        fallback_query=_drop_generic_suffix(heading),
        countrycodes="us" if k in us_bare else None,
        label_base=heading,
        bare_single_word=len(tokens(heading)) == 1,
    )


