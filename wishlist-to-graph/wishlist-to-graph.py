def static_context(name: str) -> tuple[list[str], list[str]]:
    """The states/provinces and country codes a heading names by itself, without any lookup (pure)."""
    h = normalize_heading(name)
    if h.status == "skipped":
        return [], []
    states: list[str] = []
    ccs: list[str] = []

    def add(part: str) -> None:
        key = fold(part)
        if key in STATE_CC:
            states.append(STATE_NAME[key])
            ccs.append(STATE_CC[key])
        elif part == "New York City":
            states.append("New York")
            ccs.append("us")
        elif part in COUNTRY_CODES:
            ccs.append(COUNTRY_CODES[part])
        elif part in CONTEXT_COUNTRIES:
            ccs.append(CONTEXT_COUNTRIES[part])

    if h.status == "manual" or h.canonical:
        region_states, region_ccs = REGION_CONTEXT.get(h.label_base, ([], []))
        states += region_states
        ccs += region_ccs
        if h.label_base in CANON_STATE:
            add(CANON_STATE[h.label_base])
        add(h.label_base)
        if h.query:
            for part in h.query.split(", ")[1:]:
                add(part)
        if h.countrycodes:
            ccs.append(h.countrycodes)
    elif h.featuretype == "state" and h.label_base.endswith(" State"):
        add(h.label_base[: -len(" State")])
    elif h.qualifier_label is not None and h.query:
        for part in h.query.split(", ")[1:]:
            add(part)
    else:
        key = fold(h.label_base)
        if key in {"washington"}:  # the state or the capital: either way the US
            ccs.append("us")
        elif key != "georgia":  # the state or the country
            add(h.label_base)
    return list(dict.fromkeys(states)), list(dict.fromkeys(ccs))


@dataclass
class BookContext:
    """States and countries named by the other places on the same books, most frequent first."""

    states: list[str]
    ccs: list[str]

    @classmethod
    def from_siblings(cls, siblings: list[str]) -> "BookContext":
        state_count: dict[str, int] = {}
        cc_count: dict[str, int] = {}
        for sibling in siblings:
            states, ccs = static_context(sibling)
            for state in states:
                state_count[state] = state_count.get(state, 0) + 1
            for cc in ccs:
                cc_count[cc] = cc_count.get(cc, 0) + 1
        order = lambda counts: [k for k, _ in sorted(counts.items(), key=lambda kv: -kv[1])]  # noqa: E731 (stable)
        return cls(order(state_count), order(cc_count))

    def __bool__(self) -> bool:
        return bool(self.states or self.ccs)

    def level(self, result: dict[str, Any]) -> int:
        """2: in one of the states; 1: in one of the countries; 0: outside."""
        if result.get("state") and fold(result["state"]) in {fold(s) for s in self.states}:
            return 2
        if (result.get("country_code") or "").lower() in self.ccs:
            return 1
        return 0

    def describe(self) -> str:
        return ", ".join(self.states[:3] + [cc.upper() for cc in self.ccs[:3]])

    def hints(self, heading: str) -> list[tuple[str, str | None]]:
        """At most two extra queries: '<heading>, <top state>' and '<heading>' restricted to the top country."""
        out: list[tuple[str, str | None]] = []
        if self.states:
            out.append((f"{heading}, {self.states[0]}", STATE_CC.get(fold(self.states[0]))))
        if self.ccs:
            out.append((heading, self.ccs[0]))
        return out


# Author citizenship (CITIZEN_OF, from Wikidata P27) -> country code, used as context for a birthplace that has
# no book of its own. Historical states (Russian Empire, Soviet Union, Czechoslovakia, German Reich, Cisleithania,
# Yugoslavia, Ancient Rome, ...) and "statelessness" are left out on purpose: their borders say little about
# where a town lies today.
CITIZEN_COUNTRIES = {
    "United Kingdom of Great Britain and Ireland": "gb", "Kingdom of the Netherlands": "nl",
    "People's Republic of China": "cn", "Kingdom of Denmark": "dk", "Zambia": "zm", "Uruguay": "uy",
    "Mauritius": "mu", "Serbia": "rs",
}
CITIZEN_HISTORICAL = {"Russian Empire", "Soviet Union", "Empire of Japan", "German Reich", "Czechoslovakia",
                      "Cisleithania", "Socialist Federal Republic of Yugoslavia", "Ancient Rome", "statelessness",
                      "Russian Socialist Federative Soviet Republic", "Russian Soviet Federative Socialist Republic"}


def citizenship_context(countries: list[str]) -> BookContext:
    """Context for a birthplace from its authors' citizenships, most frequent first (pure)."""
    cc_count: dict[str, int] = {}
    for country in countries:
        if not isinstance(country, str) or country in CITIZEN_HISTORICAL:
            continue
        cc = CITIZEN_COUNTRIES.get(country) or COUNTRY_CODES.get(country) or CONTEXT_COUNTRIES.get(country)
        if cc:
            cc_count[cc] = cc_count.get(cc, 0) + 1
    return BookContext([], [k for k, _ in sorted(cc_count.items(), key=lambda kv: -kv[1])])


def is_unqualified(heading: GeoHeading) -> bool:
    return heading.status == "lookup" and not heading.canonical and heading.qualifier_label is None and not heading.featuretype


def sibling_qualified(name: str, siblings: list[str]) -> GeoHeading | None:
    """A bare heading that shares a book with "<same name> (<qualifier>)" borrows that heading's lookup,
    when exactly one such target exists ("Osage County" + "Osage County (Okla.)")."""
    key = fold(name)
    found: dict[tuple[Any, ...], GeoHeading] = {}
    for sibling in siblings:
        match = QUALIFIED.match(re.sub(r"\s+", " ", sibling).strip())
        if not match or fold(match.group("base")) != key:
            continue
        h = normalize_heading(sibling)
        if h.status == "skipped":
            continue
        found[(h.status, h.query, h.countrycodes, h.featuretype, h.lat, h.lon)] = h
    return next(iter(found.values())) if len(found) == 1 else None


def choose(results: list[dict[str, Any]], heading: GeoHeading, query: str,
           context: BookContext | None = None, strict: bool = False
           ) -> tuple[dict[str, Any] | None, str | None, dict[str, Any] | None]:
    """(accepted result or None, why a result outside the book's region was refused or None, fallback or None).
    The fallback is a result to use only if the later queries (the book-region hints) find nothing better.
    `strict` (for the speculative book-context queries) also requires every word of the heading, so
    "La Brea" does not match the city of Brea."""
    wanted = significant(query.split(",")[0])
    every = set(tokens(query.split(",")[0])) if strict else None
    passing: list[tuple[int, set[str], dict[str, Any]]] = []
    for result in results:
        if not type_allowed(result):
            continue
        if heading.bare_single_word and importance(result) < IMPORTANCE_FLOOR:
            continue
        tier, extra = name_tier(result, wanted, every)
        if tier and strict and extra and extra <= ADMIN_WORDS:
            continue  # a speculative query never settles for "Hamilton County" when the heading says "Hamilton"
        if tier:
            passing.append((tier, extra or set(), result))
    if not passing:
        return None, None, None
    tier, extra, chosen = passing[0]
    if tier == 2:  # matched only through namedetails ("Reno" is the Rhine's Italian name)
        primary = next(((e, r) for t, e, r in passing if t == 1), None)
        if primary is not None and importance(primary[1]) >= TIER_RATIO * importance(chosen):
            extra, chosen = primary
    if extra and extra <= ADMIN_WORDS:  # "Monterey County" listed just before the city of Monterey
        after = passing[[r for _, _, r in passing].index(chosen) + 1:]
        exact = [r for t, e, r in after if t == 1 and not e and importance(r) >= ADMIN_RATIO * importance(chosen)]
        if exact:  # the division's own town first (same state, then same country), else the first exact name
            same_state = [r for r in exact if r.get("state") and r.get("state") == chosen.get("state")]
            same_country = [r for r in exact if r.get("country_code") and r.get("country_code") == chosen.get("country_code")]
            chosen = (same_state or same_country or exact)[0]
            extra = set()
    if not context or not is_unqualified(heading):
        return chosen, None, None
    level = context.level(chosen)
    # Inside the book's countries already: move to its state only when the books stay in one country
    # (South Haven, Minn. -> South Haven, Mich.), never on a multi-country book (Norfolk stays in England).
    wanted_levels = [2] if level == 1 and len(context.ccs) <= 1 else [] if level >= 1 else [2, 1]
    division: dict[str, Any] | None = None
    for want in wanted_levels:
        for _, other_extra, other in passing:
            if other is not chosen and context.level(other) == want and (
                    importance(chosen) < WEAK_IMPORTANCE or importance(other) >= SWITCH_RATIO * importance(chosen)):
                if other_extra and other_extra <= ADMIN_WORDS and not (extra and extra <= ADMIN_WORDS):
                    division = division or other  # "Hamilton County, Texas" does not stand for a town of Hamilton
                    continue
                return other, None, None
    if division is not None and level == 0:  # ask within the region; keep the first choice as the fallback
        return None, (f"only a division inside the book's places ({context.describe()}) for {query!r}: "
                      f"{division.get('display_name')}"), chosen if importance(chosen) >= WEAK_IMPORTANCE else None
    if level >= 1:
        return chosen, None, None
    if importance(chosen) >= WEAK_IMPORTANCE:
        return chosen, None, None
    return None, (f"only results outside the book's places ({context.describe()}) for {query!r}: "
                  f"{chosen.get('display_name')} (importance {importance(chosen):.3f})"), None


def accept(results: list[dict[str, Any]], heading: GeoHeading, query: str,
           context: BookContext | None = None) -> dict[str, Any] | None:
    return choose(results, heading, query, context)[0]


def rejection(results: list[dict[str, Any]], query: str) -> str:
    if not results:
        return f"no results for {query!r}"
    kinds = ", ".join(f"{r.get('category')}/{r.get('type')}" for r in results)
    return f"no accepted result for {query!r} ({len(results)} results: {kinds})"


# Nominatim client and the on-disk cache (E8).


class GeocodeAbort(Exception):
    """The pass must stop: Nominatim refused us, or kept failing."""


def cache_key(query: str, countrycodes: str | None, featuretype: str | None) -> str:
    return f"q={fold(query)}|cc={countrycodes or ''}|ft={featuretype or ''}"


def display_path(path: str) -> str:
    home = os.path.expanduser("~")
    return "~" + path[len(home):] if path.startswith(home + os.sep) else path


class GeoCache:
    """{version, endpoint, entries: {key: {fetched, results}}}, written atomically."""

    def __init__(self, path: str) -> None:
        self.path = path
        self.entries: dict[str, Any] = {}
        self.dirty = False
        self.pending = 0

    def load(self) -> None:
        if not os.path.exists(self.path):
            return
        try:
            with open(self.path, encoding="utf-8") as handle:
                payload = json.load(handle)
            entries = payload.get("entries") if isinstance(payload, dict) else None
            if not isinstance(entries, dict):
                raise ValueError("no entries map")
            self.entries = entries
        except (OSError, ValueError) as error:
            moved = f"{self.path}.corrupt-{int(time.time())}"
            try:
                os.replace(self.path, moved)
            except OSError:
                moved = "(could not move it)"
            log(f"geocode: cache {display_path(self.path)} unreadable ({error}); moved to {moved}, starting empty")
            self.entries = {}

    def get(self, key: str) -> list[dict[str, Any]] | None:
        entry = self.entries.get(key)
        if isinstance(entry, dict) and isinstance(entry.get("results"), list):
            return entry["results"]
        return None

    def put(self, key: str, results: list[dict[str, Any]]) -> None:
        fetched = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        self.entries[key] = {"fetched": fetched, "results": results}
        self.dirty = True
        self.pending += 1
        if self.pending >= 10:
            self.flush(force=True)

    def flush(self, force: bool = False) -> None:
        """Write when dirty (every 10 new entries, or now when forced)."""
        if not self.dirty or (not force and self.pending < 10):
            return
        directory = os.path.dirname(self.path)
        tmp = os.path.join(directory, f"{os.path.basename(self.path)}.{os.getpid()}.tmp")
        payload = {"version": 1, "endpoint": NOMINATIM, "entries": self.entries}
        try:
            os.makedirs(directory, exist_ok=True)
            with open(tmp, "w", encoding="utf-8") as handle:
                json.dump(payload, handle, ensure_ascii=False, separators=(",", ":"))
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp, self.path)
        except OSError as error:
            # A full disk or read-only ~/.cache must not lose the run: keep the in-memory cache and carry on.
            try:
                os.remove(tmp)
            except OSError:
                pass
            self.pending = 0  # retry at the next flush point, not on every put()
            log(f"geocode: could not write the cache {display_path(self.path)} ({error}); continuing without it")
            return
        self.dirty = False
        self.pending = 0


def trim_result(result: dict[str, Any]) -> dict[str, Any]:
    address = result.get("address") if isinstance(result.get("address"), dict) else {}
    names: list[str] = []
    details = result.get("namedetails") if isinstance(result.get("namedetails"), dict) else {}
    for value in details.values():
        if isinstance(value, str) and value and value not in names:
            names.append(value)
    return {
        "name": result.get("name"),
        "display_name": result.get("display_name"),
        "category": result.get("category"),
        "type": result.get("type"),
        "addresstype": result.get("addresstype"),
        "place_rank": result.get("place_rank"),
        "importance": result.get("importance"),
        "lat": result.get("lat"),
        "lon": result.get("lon"),
        "osm_type": result.get("osm_type"),
        "osm_id": result.get("osm_id"),
        "country_code": address.get("country_code"),
        "state": address.get("state"),
        "country": address.get("country"),
        "names": names,
    }


def nominatim_agent(contact: str) -> str:
    agent = f"relate-book-{NAME}/{VERSION} (+https://github.com/johnymontana/relate-book"
    return agent + (f"; {contact})" if contact else ")")


class Nominatim:
    """Nominatim /search under its usage policy: <= 1 req/s, identified, cached."""

    MAX_CONSECUTIVE_ERRORS = 5

    def __init__(self, contact: str, cache: GeoCache) -> None:
        self.headers = {"User-Agent": nominatim_agent(contact), "Accept": "application/json", "Accept-Language": "en"}
        self.cache, self.requests, self.cache_hits = cache, 0, 0
        self.lookup_errors = 0
        self._consecutive_errors = 0

    def search(self, query: str, countrycodes: str | None, featuretype: str | None) -> list[dict[str, Any]] | None:
        """Trimmed results (possibly []), or None after a lookup error (not cached)."""
        key = cache_key(query, countrycodes, featuretype)
        cached = self.cache.get(key)
        if cached is not None:
            self.cache_hits += 1
            return cached
        params = {"format": "jsonv2", "limit": "3", "addressdetails": "1", "namedetails": "1", "q": query}
        if countrycodes:
            params["countrycodes"] = countrycodes
        if featuretype:
            params["featuretype"] = featuretype
        self.requests += 1
        status, body, _ = HTTP.get(
            NOMINATIM + "?" + urllib.parse.urlencode(params), headers=self.headers, min_interval=1.05, retries=4, timeout=30
        )
        if status in (401, 403):
            raise GeocodeAbort(f"Nominatim refused the request (HTTP {status}); check the User-Agent or pass --contact")
        payload: Any = None
        if status == 200:
            try:
                payload = json.loads(body.decode("utf-8"))
            except ValueError:
                payload = None
        if not isinstance(payload, list):
            self.lookup_errors += 1
            self._consecutive_errors += 1
            log(f"geocode: lookup error for {query!r} (HTTP {status})")
            if self._consecutive_errors >= self.MAX_CONSECUTIVE_ERRORS:
                raise GeocodeAbort(f"{self._consecutive_errors} consecutive Nominatim errors (last HTTP {status})")
            return None
        self._consecutive_errors = 0
        results = [trim_result(r) for r in payload if isinstance(r, dict)]
        self.cache.put(key, results)
        return results


# Labels (E10).


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * 6371.0 * math.asin(min(1.0, math.sqrt(a)))


def assign_labels(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Every located heading -> {name, label, lat, lon}; one label and one pin per place."""
    rows = [r for r in rows if r.get("name") and r.get("lat") is not None and r.get("lon") is not None]
    if not rows:
        return []
    headings = {r["name"]: normalize_heading(r["name"]) for r in rows}
    parent = list(range(len(rows)))

    def find(i: int) -> int:
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(i: int, j: int) -> None:
        a, b = find(i), find(j)
        if a != b:
            parent[max(a, b)] = min(a, b)

    by_osm: dict[str, int] = {}
    by_base: dict[str, list[int]] = {}
    for i, row in enumerate(rows):
        osm = row.get("osm")
        if osm:
            if osm in by_osm:
                union(i, by_osm[osm])
            else:
                by_osm[osm] = i
        base = fold(headings[row["name"]].label_base or row["name"])
        for j in by_base.get(base, []):
            other = rows[j]
            if haversine_km(float(row["lat"]), float(row["lon"]), float(other["lat"]), float(other["lon"])) <= 50.0:
                union(i, j)
        by_base.setdefault(base, []).append(i)

    def weight(row: dict[str, Any]) -> tuple[int, int, int, str]:
        return (-int(row.get("books") or 0), -int(row.get("authors") or 0), len(row["name"]), row["name"])

    groups: dict[int, list[dict[str, Any]]] = {}
    for i, row in enumerate(rows):
        groups.setdefault(find(i), []).append(row)

    components = []
    for members in groups.values():
        members.sort(key=weight)
        primary = members[0]
        canonical = next((m for m in members if headings[m["name"]].canonical), None)
        label = headings[(canonical or primary)["name"]].label_base or primary["name"]
        total = (-sum(int(m.get("books") or 0) for m in members), -sum(int(m.get("authors") or 0) for m in members))
        components.append({"members": members, "primary": primary, "label": label, "weight": total + weight(primary)[2:]})

    by_label: dict[str, list[dict[str, Any]]] = {}
    for component in components:
        by_label.setdefault(fold(component["label"]), []).append(component)
    for group in by_label.values():
        if len(group) < 2:
            continue
        group.sort(key=lambda c: c["weight"])
        for component in group[1:]:
            primary = component["primary"]
            suffix = headings[primary["name"]].qualifier_label or primary.get("region")
            if not suffix or fold(suffix) == fold(component["label"]):
                suffix = f"{float(primary['lat']):.2f}, {float(primary['lon']):.2f}"
            component["label"] = f"{component['label']}, {suffix}"
    # A suffixed label that still collides gets the coordinates too.
    seen: dict[str, int] = {}
    for component in sorted(components, key=lambda c: c["weight"]):
        key = fold(component["label"])
        if key in seen:
            primary = component["primary"]
            component["label"] = f"{component['label']} ({float(primary['lat']):.2f}, {float(primary['lon']):.2f})"
            key = fold(component["label"])
        seen[key] = 1

    out = []
    for component in components:
        primary = component["primary"]
        for member in component["members"]:
            out.append({"name": member["name"], "label": component["label"], "lat": float(primary["lat"]), "lon": float(primary["lon"])})
    out.sort(key=lambda r: r["name"])
    return out


