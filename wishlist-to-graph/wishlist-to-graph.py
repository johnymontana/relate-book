def fold(s: str) -> str:
    """Case-, accent- and whitespace-insensitive key for a heading."""
    s = unicodedata.normalize("NFKD", s or "")
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = s.replace("’", "'").replace("‘", "'").replace("`", "'").replace("´", "'")
    return re.sub(r"\s+", " ", s.casefold()).strip()


TOKEN_ALIASES = {"st": "saint", "ste": "sainte", "mt": "mount", "ft": "fort", "&": "and"}
MATCH_STOPWORDS = {"the", "of", "de", "la", "le", "les", "du", "del", "des", "and", "city", "state", "region", "regions", "area"}


def tokens(s: str) -> list[str]:
    parts = re.findall(r"[a-z0-9]+", fold(s).replace("'", ""))
    return [TOKEN_ALIASES.get(p, p) for p in parts]


def significant(s: str) -> set[str]:
    return {t for t in tokens(s) if t not in MATCH_STOPWORDS} or set(tokens(s))


