def type_allowed(result: dict[str, Any]) -> bool:
    category, kind = result.get("category"), result.get("type")
    if category not in ALLOWED_TYPES:
        return False
    allowed = ALLOWED_TYPES[category]
    if category == "place" and kind in PLACE_DENIED:
        return False
    return allowed is None or kind in allowed


# Review fixes to the first-passing-result rule:
# - a result whose primary `name` matches beats one that matches only through namedetails ("Reno" is not the Rhine);
# - "X County" / "X Prefecture" listed just before an exact "X" of similar importance yields to it (Monterey, Butte);
# - an unqualified heading is checked against the places of the same books (BookContext): a weak result
#   outside their states and countries is not accepted (Mann Gulch, Lisbon Falls, Cascade Range).
ADMIN_WORDS = {"county", "prefecture", "oblast", "province", "township", "parish", "kommun", "municipality", "district"}
ADMIN_RATIO = 0.85  # the exact-name result needs at least this share of the admin division's importance
WEAK_IMPORTANCE = 0.35  # below this a result outside the book's region is not trusted
SWITCH_RATIO = 0.65  # a later result inside the book's region needs this share of the first one's importance
TIER_RATIO = 0.6  # a later primary-name match beats an earlier alternate-name match only at this share of its importance


def importance(result: dict[str, Any]) -> float:
    try:
        return float(result.get("importance") or 0.0)
    except (TypeError, ValueError):
        return 0.0


def name_tier(result: dict[str, Any], wanted: set[str], every: set[str] | None = None) -> tuple[int, set[str] | None]:
    """(1, extra tokens) when the primary name matches, (2, extra) through namedetails only, (0, None) otherwise.
    `every`, when given, is a set of tokens that must all appear too, stopwords included (strict matching)."""
    def fits(variant: str) -> set[str] | None:
        got = significant(variant)
        if wanted <= got and len(got - wanted) <= 1 and (every is None or every <= set(tokens(variant))):
            return got - wanted
        return None

    extra = fits(result.get("name") or "")
    if extra is not None:
        return 1, extra
    extras = []
    for variant in result.get("names") or []:
        got = fits(variant)
        if got is not None:
            extras.append(got)
    if extras:
        return 2, min(extras, key=len)
    return 0, None


def name_matches(result: dict[str, Any], query: str) -> bool:
    return name_tier(result, significant(query.split(",")[0]))[0] > 0


