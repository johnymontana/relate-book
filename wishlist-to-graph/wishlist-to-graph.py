class OpenLibrary:
    def __init__(self, contact: str) -> None:
        agent = f"{NAME}/{VERSION} (Relate extension; https://github.com/johnymontana/relate-book"
        agent += f"; {contact})" if contact else ")"
        self.headers = {"User-Agent": agent, "Accept": "application/json"}
        # Identified clients (a contact in the User-Agent) get 3 req/s; anonymous ones 1 req/s.
        self.interval = 0.4 if contact else 1.05
        self.author_cache: dict[str, dict[str, Any] | None] = {}
        self.requests = 0

    def _json(self, path: str) -> Any:
        self.requests += 1
        return HTTP.json(OL + path, headers=self.headers, min_interval=self.interval)

    def search(self, query: dict[str, str], limit: int = 3) -> list[dict[str, Any]]:
        params = dict(query)
        params["fields"] = OL_SEARCH_FIELDS
        params["limit"] = str(limit)
        payload = self._json("/search.json?" + urllib.parse.urlencode(params))
        return payload.get("docs", []) if isinstance(payload, dict) else []

    def resolve(self, item: dict[str, Any]) -> dict[str, Any] | None:
        """The work search-doc for one Amazon item, by the strongest key first."""
        asin = item["asin"]
        docs: list[dict[str, Any]] = []
        if item["isbn10"]:
            docs = self.search({"q": f"isbn:{item['isbn10']}"}, limit=1)
        if not docs and not item["external"]:
            docs = self.search({"q": f"id_amazon:{asin}"}, limit=1)
        if not docs and item["isbn10"]:
            edition = self._json(f"/isbn/{item['isbn10']}.json")
            works = edition.get("works", []) if isinstance(edition, dict) else []
            if works:
                docs = self.search({"q": f'key:"{works[0]["key"]}"'}, limit=1)
        if docs:
            docs[0]["_match"] = "identifier"
            return docs[0]
        if not item["is_book"]:
            return None
        title = re.split(r"[:(\[]", item["title"])[0].strip()
        authors = [c["name"] for c in item["contributors"] if c["role"] == "Author"] or [c["name"] for c in item["contributors"]]
        query = {"title": title}
        if authors:
            query["author"] = authors[0]
        candidates = self.search(query, limit=5)
        if not candidates and authors:
            candidates = self.search({"title": title}, limit=5)
        for doc in candidates:
            if not authors or any(
                author.split()[-1].lower() in " ".join(doc.get("author_name", [])).lower() for author in authors
            ):
                doc["_match"] = "title"
                return doc
        return None

    def work(self, key: str) -> dict[str, Any] | None:
        payload = self._json(f"{key}.json")
        return payload if isinstance(payload, dict) else None

    def author(self, key: str) -> dict[str, Any] | None:
        if key not in self.author_cache:
            payload = self._json(f"{key}.json")
            self.author_cache[key] = payload if isinstance(payload, dict) else None
        return self.author_cache[key]


def ol_text(value: Any) -> str | None:
    if isinstance(value, dict):
        value = value.get("value")
    if isinstance(value, str):
        value = value.strip()
        return value or None
    return None


def pick_edition(doc: dict[str, Any], item: dict[str, Any]) -> dict[str, Any]:
    """The matching edition sub-doc (filtered by the query) or an empty map."""
    editions = doc.get("editions", {}).get("docs", []) if isinstance(doc.get("editions"), dict) else []
    for edition in editions:
        amazon_ids = edition.get("id_amazon", [])
        isbns = edition.get("isbn", [])
        if item["asin"] in amazon_ids or (item["isbn10"] and (item["isbn10"] in isbns or item["isbn13"] in isbns)):
            return edition
    return editions[0] if editions else {}


