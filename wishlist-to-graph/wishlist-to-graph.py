#!/usr/bin/env python3
"""wishlist-to-graph — an Amazon wishlist as a reading-list graph (a Relate extension).

The host (`relate run wishlist-to-graph`) spawns this file, hands it the
manifest's flag values as one JSON envelope line on stdin, and from then on
the two pipes carry JSON-RPC 2.0: this process is the MCP client, the host
is the MCP server that alone owns the store.

What it does
------------
1. Fetches a *public* Amazon wishlist (every page — the list paginates with a
   `lastEvaluatedKey` cursor behind the "See more" link), or parses a page
   you saved from the browser (`--html-file`, the route for private lists).
2. Writes every row as an `(:Item)`; rows that look like books (binding in
   the byline — Paperback, Hardcover, Kindle Edition, … — or an ASIN that is
   a valid ISBN-10) also get the `:Edition` label.
3. Enriches each edition from Open Library (ASIN → edition → work → authors,
   subjects, places, characters, ratings, reading-log counts, description,
   first sentence, cover, Goodreads/Wikidata ids). Optional extra sources:
   Google Books (`--google-books`, needs GOOGLE_BOOKS_API_KEY), Hardcover
   (`--hardcover`, needs HARDCOVER_API_TOKEN) and Wikidata (`--wikidata`,
   no key: author nationality / birthplace / occupations / awards, and work
   genres, awards and series when Open Library knows the work's QID).

Graph model
-----------
  (:Wishlist)-[:CONTAINS {priority, comment, date_added, ...}]->(:Item)
  (:Item:Edition)-[:EDITION_OF]->(:Book)
  (:Item:Edition)-[:PUBLISHED_BY]->(:Publisher)
  (:Book)-[:WRITTEN_BY]->(:Author)
  (:Book)-[:ABOUT]->(:Subject)      (:Book)-[:SET_IN]->(:Place)
  (:Book)-[:FEATURES]->(:Person)    (:Book)-[:SET_DURING]->(:Era)
  (:Book)-[:IN_GENRE]->(:Genre)     (:Book)-[:PART_OF {position}]->(:Series)
  (:Book)-[:WON {year}]->(:Award)   (:Author)-[:WON]->(:Award)
  (:Author)-[:CITIZEN_OF]->(:Country)   (:Author)-[:BORN_IN]->(:Place)
  (:Place {location: point, geocoded_label, geo_*})   (with --geocode)

`--geocode` geocodes every Place heading without a location through
Nominatim (1 request per second, cached in ~/.cache/relate-book/geocode.json);
with no WISHLIST it runs on the existing store alone. `--self-test` runs the
offline checks of the heading normalizer, the result filter and the labels.

Standard library only: python3 (3.10+) is the whole runtime. The MCP glue
(the `Client` class) is the one `relate extension init --lang py` generates;
its source of truth is docs/api/extensions/spec.md, "The Transport contract".
"""

